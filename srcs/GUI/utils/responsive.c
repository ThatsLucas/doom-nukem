#include "GUI.h"
#include "Window.h"

void to_responsive(t_WIN *win, SDL_Rect *cur)
{
    cur->w = (cur->w * win->w) / 1920;
    cur->h = (cur->h * win->h) / 1080;
    cur->x = (cur->x * win->w) / 1920;
    cur->y = (cur->y * win->h) / 1080;
}